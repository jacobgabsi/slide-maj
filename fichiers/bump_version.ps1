param(
    [string]$dir        # répertoire du projet
)

$ErrorActionPreference = 'Stop'
$ci = [System.Globalization.CultureInfo]::InvariantCulture

# Empreinte des SOURCES : on n'incrémente que si quelque chose a réellement changé.
# Même principe que bump_version.ps1 de PennyTop, mais sur les sources et non sur l'exe :
# ici le numéro doit être connu AVANT la compilation, puisqu'il est compilé dans l'exe
# (Module1.SlideVersion -> affiché par Form1 et utilisé par SaveVersion).
# VersionAuto.vb est exclu de l'empreinte (il change à chaque incrément, ce qui
# déclencherait un incrément à chaque compilation suivante), ainsi que bin/obj/.vs.
$fichiers = Get-ChildItem -Path $dir -Recurse -File -Include *.vb, *.resx, *.vbproj, *.config |
            Where-Object { $_.FullName -notmatch '\\(bin|obj|\.vs|Publication|maj)\\' -and $_.Name -ne 'VersionAuto.vb' } |
            Sort-Object FullName

if (-not $fichiers) { exit 0 }

$sb = New-Object System.Text.StringBuilder
foreach ($f in $fichiers) {
    [void]$sb.Append($f.Name)
    [void]$sb.Append((Get-FileHash -Path $f.FullName -Algorithm SHA256).Hash)
}
$sha  = [System.Security.Cryptography.SHA256]::Create()
$hash = [BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($sb.ToString()))).Replace('-','')

$hashFile = Join-Path $dir '.version_hash'
$prevHash = if (Test-Path $hashFile) { (Get-Content $hashFile -Raw).Trim() } else { '' }

$verFile  = Join-Path $dir 'version.txt'
$vbFile   = Join-Path $dir 'VersionAuto.vb'

if ($hash -eq $prevHash -and (Test-Path $vbFile)) { exit 0 }   # rien n'a changé -> pas d'incrément

# Lecture de la version courante
if (Test-Path $verFile) {
    $cur = [double]::Parse((Get-Content $verFile -Raw).Trim(), $ci)
} else {
    $cur = 7.992
}

# Incrément de 0.001
$new    = [math]::Round($cur + 0.001, 3)
$newStr = $new.ToString('0.000', $ci)

# Sauvegardes (version.txt sans BOM)
[System.IO.File]::WriteAllText($verFile, $newStr)
[System.IO.File]::WriteAllText($hashFile, $hash)

# Fichier source généré, lu par Module1.SlideVersion.
# Écrit AVANT CoreCompile : c'est bien ce numéro-là qui part dans l'exe.
$vb = @"
'------------------------------------------------------------------------------
' <auto-generated>
'     Fichier GENERE par bump_version.ps1 a chaque compilation reelle.
'     Ne pas modifier a la main : toute modification sera ecrasee.
'     Le numero de reference est dans version.txt.
' </auto-generated>
'------------------------------------------------------------------------------

Module VersionAuto

    ''' <summary>Version de l'application, incrementee de 0,001 a chaque compilation.</summary>
    Public Const SlideVersionAuto As String = "$newStr"

End Module
"@
[System.IO.File]::WriteAllText($vbFile, $vb, (New-Object Text.UTF8Encoding($true)))

Write-Host "Version compilee : Slide $newStr"
